/* ==========================================================================
   Login Management Script (Strict Authentication with Supabase Auth Email)
   ========================================================================== */

document.addEventListener('DOMContentLoaded', () => {
    // ==========================================
    // App Splash & Loading Screen Injection
    // ==========================================
    const injectAppLoader = () => {
        if (document.getElementById('appSplashLoader')) return;

        const loaderHTML = `
            <div id="appSplashLoader" style="
                position: fixed;
                top: 0;
                left: 0;
                width: 100vw;
                height: 100vh;
                background-color: #ffffff;
                display: flex;
                flex-direction: column;
                justify-content: center;
                align-items: center;
                z-index: 999999;
                transition: opacity 0.4s ease;
            ">
                <div id="splashLogo" style="
                    width: 90px;
                    height: 90px;
                    margin-bottom: 20px;
                    animation: logoFlash 1.2s infinite alternate ease-in-out;
                    display: flex;
                    justify-content: center;
                    align-items: center;
                ">
                    <!-- আপনার assets ফোল্ডারের নিজস্ব লোগো ইমেজ -->
                    <img src="assets/logo.png" alt="SafePass Vault Logo" style="
                        width: 100%;
                        height: 100%;
                        object-fit: contain;
                    " />
                </div>
                <div class="spinner-clockwise" style="
                    width: 36px;
                    height: 36px;
                    border: 4px solid #e5e7eb;
                    border-top: 4px solid #2c5364;
                    border-radius: 50%;
                    animation: spinClockwise 0.8s linear infinite;
                    margin-bottom: 15px;
                "></div>
                <p style="
                    font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
                    font-size: 15px;
                    font-weight: 600;
                    color: #374151;
                    letter-spacing: 0.5px;
                    margin: 0;
                ">Loading please wait</p>
            </div>

            <style>
                @keyframes logoFlash {
                    0% { opacity: 0.3; transform: scale(0.95); }
                    100% { opacity: 1; transform: scale(1.05); }
                }
                @keyframes spinClockwise {
                    0% { transform: rotate(0deg); }
                    100% { transform: rotate(360deg); }
                }
            </style>
        `;

        document.body.insertAdjacentHTML('afterbegin', loaderHTML);

        // সার্ভার সচল রাখতে দ্রুত লোডার ফেডআউট করে দেওয়া হলো যাতে বেশিক্ষণ অপেক্ষা করতে না হয়
        setTimeout(() => {
            const loader = document.getElementById('appSplashLoader');
            if (loader) {
                loader.style.opacity = '0';
                setTimeout(() => loader.remove(), 400);
            }
        }, 800);
    };

    // পেজ লোড হওয়ার সাথে সাথেই স্প্ল্যাশ লোডার রান করবে
    injectAppLoader();

    // ==========================================
    // Supabase Initialization
    // ==========================================
    const SUPABASE_URL = 'https://vgjsoicsmmzahhsuworg.supabase.co';
    const SUPABASE_ANON_KEY = 'sb_publishable_NkMibVnz7Vt6CAHuSTaQZw_zpUFGNsv'; 
    
    let supabase = null;
    if (window.supabase) {
        supabase = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
    } else {
        console.error("Supabase client library missing! Make sure Supabase JS CDN script is included in HTML before script.js.");
    }

    // Form & Input Elements
    const loginForm = document.getElementById('loginForm');
    const identifierInput = document.getElementById('identifier');
    const passwordInput = document.getElementById('password');
    const userIdGroup = document.getElementById('userIdGroup');
    const autoGeneratedUserIdInput = document.getElementById('autoGeneratedUserId');
    const loginBtn = document.getElementById('loginBtn');
    
    // Error Modal Elements
    const errorModal = document.getElementById('errorModal');
    const errorTitle = document.getElementById('errorTitle');
    const errorMessage = document.getElementById('errorMessage');
    const closeModalBtn = document.getElementById('closeModalBtn');
    
    // Forgot Password Modal Elements
    const forgotPasswordLink = document.getElementById('forgotPasswordLink');
    const forgotPromptModal = document.getElementById('forgotPromptModal');
    const resetIdentifierInput = document.getElementById('resetIdentifierInput');
    const submitForgotBtn = document.getElementById('submitForgotBtn');
    const cancelForgotBtn = document.getElementById('cancelForgotBtn');

    let isUserIdVerified = false;

    // Helper Function: Show Custom Error Modal
    const showErrorModal = (title, msg) => {
        if (errorTitle) errorTitle.innerText = title;
        if (errorMessage) errorMessage.innerText = msg;
        if (errorModal) errorModal.style.display = 'flex';
    };

    if (closeModalBtn) {
        closeModalBtn.addEventListener('click', () => {
            if (errorModal) errorModal.style.display = 'none';
        });
    }

    // Modal Background Click Dismiss
    window.addEventListener('click', (e) => {
        if (e.target === errorModal) errorModal.style.display = 'none';
        if (e.target === forgotPromptModal) forgotPromptModal.style.display = 'none';
    });

    // Validation Helpers
    const isValidEmail = (email) => {
        return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
    };

    const isValidBangladeshiPhone = (phone) => {
        return /^01[3-9]\d{8}$/.test(phone);
    };

    // Prevent Copy-Paste Security on Password Input
    if (passwordInput) {
        ['copy', 'paste', 'cut', 'drop'].forEach(eventType => {
            passwordInput.addEventListener(eventType, (e) => {
                e.preventDefault();
                showErrorModal("Security Restriction", "For security reasons, copy-pasting passwords is restricted. Please type manually.");
            });
        });
    }

    // Helper: Find User strictly by Email
    const findUserByEmail = async (email) => {
        const cleanEmail = email ? email.trim().toLowerCase() : '';
        if (!cleanEmail) return null;

        if (supabase && navigator.onLine) {
            try {
                const { data: allData, error: allError } = await supabase.from('users').select('*');
                if (!allError && allData && allData.length > 0) {
                    const matched = allData.find(u => {
                        const uEmail = (u.email || '').trim().toLowerCase();
                        return uEmail === cleanEmail;
                    });
                    if (matched) return matched;
                }
            } catch (err) {
                console.warn("Supabase fetch exception, falling back to local storage:", err);
            }
        }

        const localRegistered = JSON.parse(localStorage.getItem('registeredUsers') || '[]');
        const localFound = localRegistered.find(u => u.email && u.email.trim().toLowerCase() === cleanEmail);
        if (localFound) return localFound;

        const singleUserStr = localStorage.getItem('safePassUser') || localStorage.getItem('user');
        if (singleUserStr) {
            try {
                const parsed = JSON.parse(singleUserStr);
                if (parsed.email && parsed.email.trim().toLowerCase() === cleanEmail) {
                    return parsed;
                }
            } catch (err) {
                console.error(err);
            }
        }

        return null;
    };

    // Helper: Find User in Supabase Table safely & Locally (For general login)
    const findUserByIdentifier = async (identifier) => {
        const cleanIdentifier = identifier ? identifier.trim() : '';
        if (!cleanIdentifier) return null;

        if (supabase && navigator.onLine) {
            try {
                const { data: allData, error: allError } = await supabase.from('users').select('*');
                if (!allError && allData && allData.length > 0) {
                    const matched = allData.find(u => {
                        const uEmail = (u.email || '').trim().toLowerCase();
                        const uPhone = (u.phone || '').trim();
                        const uPhoneNumber = (u.phoneNumber || '').trim();
                        const uUserId = (u.userId || '').trim();
                        const uId = (u.id || '').trim();
                        const target = cleanIdentifier.toLowerCase();

                        return uEmail === target || 
                               uPhone === cleanIdentifier || 
                               uPhoneNumber === cleanIdentifier || 
                               uUserId === cleanIdentifier || 
                               uId === cleanIdentifier;
                    });
                    if (matched) return matched;
                }
            } catch (err) {
                console.warn("Supabase fetch exception, falling back to local storage:", err);
            }
        }

        const localRegistered = JSON.parse(localStorage.getItem('registeredUsers') || '[]');
        const localFound = localRegistered.find(u => 
            (u.email && u.email.toLowerCase() === cleanIdentifier.toLowerCase()) || 
            (u.phoneNumber && u.phoneNumber === cleanIdentifier) ||
            (u.phone && u.phone === cleanIdentifier) ||
            (u.userId && u.userId === cleanIdentifier) ||
            (u.id && u.id === cleanIdentifier)
        );
        if (localFound) return localFound;

        const singleUserStr = localStorage.getItem('safePassUser') || localStorage.getItem('user');
        if (singleUserStr) {
            try {
                const parsed = JSON.parse(singleUserStr);
                if (
                    (parsed.email && parsed.email.toLowerCase() === cleanIdentifier.toLowerCase()) ||
                    (parsed.phoneNumber && parsed.phoneNumber === cleanIdentifier) ||
                    (parsed.userId && parsed.userId === cleanIdentifier)
                ) {
                    return parsed;
                }
            } catch (err) {
                console.error(err);
            }
        }

        return null;
    };

    // Forgot Password Link Click
    if (forgotPasswordLink) {
        forgotPasswordLink.addEventListener('click', (e) => {
            e.preventDefault();

            if (!navigator.onLine) {
                showErrorModal("No Internet", "Please check your internet connection to reset your password.");
                return;
            }

            if (forgotPromptModal) forgotPromptModal.style.display = 'flex';
        });
    }

    if (cancelForgotBtn) {
        cancelForgotBtn.addEventListener('click', () => {
            if (forgotPromptModal) forgotPromptModal.style.display = 'none';
        });
    }

    // Forgot Password Request Submit Handler
    if (submitForgotBtn) {
        submitForgotBtn.addEventListener('click', async () => {
            const inputVal = resetIdentifierInput ? resetIdentifierInput.value.trim() : '';

            if (!inputVal) {
                showErrorModal("Input Required", "Please enter your registered email address.");
                return;
            }

            if (!isValidEmail(inputVal)) {
                if (forgotPromptModal) forgotPromptModal.style.display = 'none';
                if (resetIdentifierInput) resetIdentifierInput.value = '';
                showErrorModal("Invalid Input!", "Password recovery is only allowed using your registered email address.");
                return;
            }

            if (!navigator.onLine) {
                showErrorModal("No Internet", "Internet connection is required to submit password reset request.");
                return;
            }

            try {
                submitForgotBtn.disabled = true;
                submitForgotBtn.innerText = "Sending...";

                const existingUser = await findUserByEmail(inputVal);

                if (existingUser) {
                    if (supabase) {
                        const redirectToUrl = window.location.origin + '/reset-password.html';
                        
                        const { error: authError } = await supabase.auth.resetPasswordForEmail(inputVal, {
                            redirectTo: redirectToUrl,
                        });

                        if (authError) {
                            console.warn("Supabase Auth mail warning:", authError.message);
                        }
                    }

                    if (forgotPromptModal) forgotPromptModal.style.display = 'none';
                    if (resetIdentifierInput) resetIdentifierInput.value = '';

                    showErrorModal("Email Sent!", "A password reset link has been sent successfully to your inbox.\nPlease check your email (and spam folder).");
                } else {
                    if (forgotPromptModal) forgotPromptModal.style.display = 'none';
                    if (resetIdentifierInput) resetIdentifierInput.value = '';
                    showErrorModal("Email Not Found!", "This email address is not registered in our system.");
                }
            } catch (err) {
                console.error("Forgot password request error:", err);
                showErrorModal("Error", "Failed to submit request.");
            } finally {
                submitForgotBtn.disabled = false;
                submitForgotBtn.innerText = "Submit Request";
            }
        });
    }

    // Form Submission Handler (Strict Login)
    if (loginForm) {
        loginForm.addEventListener('submit', async (e) => {
            e.preventDefault();

            if (isUserIdVerified) {
                window.location.href = "dashboard.html";
                return;
            }

            const identifier = identifierInput ? identifierInput.value.trim() : '';
            const password = passwordInput ? passwordInput.value : '';

            if (!identifier || !password) {
                if (userIdGroup) userIdGroup.style.display = 'none';
                showErrorModal("Login Failed!", "Please provide both Email/Phone/User ID and Password.");
                return;
            }

            try {
                if (loginBtn) {
                    loginBtn.disabled = true;
                    loginBtn.innerText = "Verifying...";
                }

                const rawUser = await findUserByIdentifier(identifier);

                let isPasswordValid = false;
                if (rawUser) {
                    if (rawUser.password === password) {
                        isPasswordValid = true;
                    }
                }

                if (isPasswordValid && rawUser) {
                    const finalUserId = (rawUser.userId || rawUser.id || identifier).toString().trim();

                    const standardizedUser = {
                        userId: finalUserId,
                        id: finalUserId,
                        _id: rawUser._id || rawUser.id || finalUserId,
                        fullName: rawUser.fullName || rawUser.name || rawUser.userName || "User",
                        email: rawUser.email || (isValidEmail(identifier) ? identifier : ""),
                        phoneNumber: rawUser.phoneNumber || rawUser.phone || (isValidBangladeshiPhone(identifier) ? identifier : "")
                    };

                    if (autoGeneratedUserIdInput && userIdGroup) {
                        autoGeneratedUserIdInput.value = finalUserId;
                        userIdGroup.style.display = 'block';
                    }

                    localStorage.setItem('isLoggedIn', 'true');
                    localStorage.setItem('safePassUser', JSON.stringify(standardizedUser));
                    localStorage.setItem('user', JSON.stringify(standardizedUser));
                    localStorage.setItem('currentUser', JSON.stringify(standardizedUser));
                    localStorage.setItem('savedUserIdNumber', finalUserId);

                    isUserIdVerified = true;

                    let secondsLeft = 3;
                    if (loginBtn) loginBtn.innerText = `Redirecting in ${secondsLeft}s...`;

                    const countdownInterval = setInterval(() => {
                        secondsLeft -= 1;
                        if (secondsLeft > 0) {
                            if (loginBtn) loginBtn.innerText = `Redirecting in ${secondsLeft}s...`;
                        } else {
                            clearInterval(countdownInterval);
                            window.location.href = "dashboard.html";
                        }
                    }, 1000);

                } else {
                    if (userIdGroup) userIdGroup.style.display = 'none';
                    if (loginBtn) {
                        loginBtn.disabled = false;
                        loginBtn.innerText = "Login";
                    }
                    showErrorModal("Login Failed!", "Account not found or incorrect password. Please register first.");
                }

            } catch (error) {
                console.error("Login Error:", error);
                if (userIdGroup) userIdGroup.style.display = 'none';
                if (loginBtn) {
                    loginBtn.disabled = false;
                    loginBtn.innerText = "Login";
                }
                showErrorModal("Server Error", "Unable to process login right now.");
            }
        });
    }
});